def split_by_token(text, chunk_size=300, chunk_overlap=50):
    tokens = tokenizer.encode(text)
    chunks = []
    start = 0
    while start < len(tokens):
        end = min(start + chunk_size, len(tokens))
        chunk_tokens = tokens[start:end]
        chunk_text = tokenizer.decode(chunk_tokens, skip_special_tokens=True)
        chunks.append(chunk_text)
        start += chunk_size - chunk_overlap
    return chunks

def generate_metadata_with_llm_per_key(llm, text_chunk):
    meta = {}
    for key, template in PROMPTS.items():
        prompt = template.format(text=text_chunk)
        result = llm(prompt)
        meta[key] = result.strip()
    return meta

def add_text_knowledge_to_vectordb(vectordb, text):
    chunks = split_by_token(text)
    documents = []
    for idx, chunk in enumerate(chunks):
        meta = generate_metadata_with_llm_per_key(llm, chunk)
        meta["chunk_id"] = idx + 1
        doc = Document(
            page_content=chunk,
            metadata=meta
        )
        documents.append(doc)
    
    vectordb.add_documents(documents, embedding=embedding_model)
    vectordb.persist()
    print(f"✅ เพิ่ม knowledge {len(documents)} chunk เข้า VectorDB พร้อม metadata แล้ว!")

